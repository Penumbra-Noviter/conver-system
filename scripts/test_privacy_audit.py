"""privacy_audit 模块测试：pubspec.lock 解析 + 追踪-SDK 排除名单命中检测。

契约（与 docs/privacy-android.md 口径一致）：
- 「零第三方 SDK 追踪」= 依赖树（pubspec.lock 直接 + 传递全量包名）命中排除名单条数为 0；
- 排除名单按「包名字串子串」匹配——负样本（含 appsflyer / sentry 等模拟条目）必须能被命中；
- 既有功能库（drift / dio / flutter_secure_storage / webview_flutter / share_plus /
  path_provider 等）不得命中名单；
- 空依赖样本通过（无漏报误报）。
"""

