class TestTrackingDetection:
    FAKE_TRACKING = {
        "firebase_core": "transitive",
        "appsflyer_sdk": "transitive",
        "sentry_flutter": "direct main",
        "amplitude_flutter": "transitive",
        "mixpanel_flutter": "transitive",
        "adjust_sdk": "transitive",
        "braze_plugin": "transitive",
        "flutter_branch_sdk": "transitive",
        "clevertap_flutter": "transitive",
        "kochava_flutter": "transitive",
        "firebase_crashlytics": "transitive",
    }

    def test_negative_sample_all_hit(self):
        result = audit_lockfile(_lock_text(self.FAKE_TRACKING))
        assert result.package_count == len(self.FAKE_TRACKING)
        assert set(result.hits) == set(self.FAKE_TRACKING)
        assert not result.is_clean

    def test_functional_libraries_not_hit(self):
        functional = {
            "drift": "direct main",
            "dio": "direct main",
            "flutter_secure_storage": "direct main",
            "webview_flutter": "direct main",
            "share_plus": "direct main",
            "path_provider": "direct main",
            "provider": "direct main",
            "crypto": "direct main",
            "file_picker": "direct main",
            "sqlite3": "transitive",
            "markdown": "transitive",
            "flutter_markdown_plus": "direct main",
        }
        result = audit_lockfile(_lock_text(functional))
        assert result.hits == ()
        assert result.is_clean

    def test_custom_and_empty_patterns(self):
        text = _lock_text({"sentry_flutter": "transitive"})
        assert audit_lockfile(text, patterns=("sent",)).hits == ("sentry_flutter",)
        assert audit_lockfile(text, patterns=()).hits == ()

    def test_empty_lock_audit_clean(self):
        result = audit_lockfile("")
        assert result.package_count == 0
        assert result.hits == ()
        assert result.is_clean

    def test_lockfile_str_content_object(self):
        text = _lock_text(
            {"dio": "direct main", "sentry_flutter": "transitive"}
        )
        result = audit_lockfile(text)
        assert result.package_count == 2
        assert result.hits == ("sentry_flutter",)

    def test_lockfile_str_missing_packages(self):
        assert audit_lockfile("sdks:\n  dart: x\n").package_count == 0
        assert audit_lockfile("").package_count == 0
        assert audit_lockfile("packages: not-a-section\n").package_count == 0

    def test_lockfile_dict_input_rejected(self):
        with pytest.raises(TypeError):
            audit_lockfile({"packages": {"dio": {"dependency": "direct main"}}})


