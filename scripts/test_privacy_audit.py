class TestAuditProject:
    def test_clean_project(self, tmp_path):
        _write_project(
            tmp_path,
            "name: demo\ndependencies:\n  dio: ^5.11.0\n  drift: ^2.34.3\n"
            "dev_dependencies:\n  flutter_lints: ^6.0.0\n",
            _lock_text(
                {
                    "dio": "direct main",
                    "drift": "direct main",
                    "flutter_lints": "direct dev",
                }
            ),
        )
        result = audit_project(tmp_path)
        assert result.package_count == 3
        assert result.hits == ()
        assert result.unresolved_direct == ()
        assert result.is_clean

    def test_unresolved_direct_detected(self, tmp_path):
        _write_project(
            tmp_path,
            "name: demo\ndependencies:\n  appsflyer_sdk: ^1.0.0\n",
            _lock_text({"dio": "transitive"}),
        )
        result = audit_project(tmp_path)
        assert result.unresolved_direct == ("appsflyer_sdk",)
        assert not result.is_clean

    def test_missing_input_files_raise(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            audit_project(tmp_path)
        (tmp_path / "pubspec.yaml").write_text("name: demo\n", encoding="utf-8")
        with pytest.raises(FileNotFoundError):
            audit_project(tmp_path)


class TestCli:
    def test_main_clean_exit_zero(self, tmp_path, capsys, monkeypatch):
        _write_project(
            tmp_path,
            "name: demo\ndependencies:\n  dio: ^5.11.0\n",
            _lock_text({"dio": "direct main"}),
        )
        monkeypatch.chdir(tmp_path)
        assert main([]) == 0
        out = capsys.readouterr().out
        assert "OK" in out
        assert "零第三方 SDK 追踪" in out

    def test_main_hits_exit_one(self, tmp_path, capsys, monkeypatch):
        _write_project(
            tmp_path,
            "name: demo\ndependencies:\n  sentry_flutter: ^1.0.0\n",
            _lock_text({"sentry_flutter": "direct main"}),
        )
        monkeypatch.chdir(tmp_path)
        assert main([]) == 1
        out = capsys.readouterr().out
        assert "sentry_flutter" in out

    def test_main_missing_lock_exit_one(self, tmp_path, capsys, monkeypatch):
        (tmp_path / "pubspec.yaml").write_text("name: demo\n", encoding="utf-8")
        monkeypatch.chdir(tmp_path)
        assert main([]) == 1
        out = capsys.readouterr().out
        assert "缺少审计输入" in out

    def test_main_unresolved_direct_exit_one(self, tmp_path, capsys, monkeypatch):
        _write_project(
            tmp_path,
            "name: demo\ndependencies:\n  appsflyer_sdk: ^1.0.0\n",
            _lock_text({"dio": "transitive"}),
        )
        monkeypatch.chdir(tmp_path)
        assert main([]) == 1
        out = capsys.readouterr().out
        assert "未在 pubspec.lock 解析" in out


class TestCliAsScript:
    def test_run_as_script_on_real_repo_exit_zero(self):
        # 以脚本方式执行（覆盖 __main__ 守卫），对真实 worktree 跑一遍完整审计
        proc = __import__("subprocess").run(
            [sys.executable, "scripts/privacy_audit.py"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        assert proc.returncode == 0
        assert "零第三方 SDK 追踪" in proc.stdout


