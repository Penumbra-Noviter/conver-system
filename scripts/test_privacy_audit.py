def _lock_text(packages: dict[str, str]) -> str:
    """构造最小合法 pubspec.lock 文本：包名 -> dependency 类型（transitive / direct main）。"""
    lines = ["# Generated by pub", "packages:"]
    for name, kind in packages.items():
        lines.append(f"  {name}:")
        lines.append(f"    dependency: {kind}")
        lines.append("    description:")
        lines.append(f"      name: {name}")
        lines.append('      url: "https://pub.dev"')
        lines.append("    source: hosted")
        lines.append('    version: "1.0.0"')
    lines.append("sdks:")
    lines.append('  dart: ">=3.13.2 <4.0.0"')
    return "\n".join(lines)


def _write_project(tmp_path: Path, pubspec: str, lock: str) -> None:
    (tmp_path / "pubspec.yaml").write_text(pubspec, encoding="utf-8")
    (tmp_path / "pubspec.lock").write_text(lock, encoding="utf-8")


class TestParseLock:
    def test_parse_real_lock_full_count_and_kinds(self):
        pkgs = parse_lock_packages(LOCK.read_text(encoding="utf-8"))
        assert len(pkgs) >= 100
        by = {p.name: p for p in pkgs}
        assert by["dio"].dependency_kind == "direct main"
        assert by["analyzer"].dependency_kind == "transitive"
        assert by["flutter"].source == "sdk"
        assert by["flutter"].dependency_kind == "direct main"
        assert by["flutter_secure_storage"].version == "11.0.0"
        assert "sdks" not in by  # sdks 段不得混入包名单

    def test_empty_lock_returns_no_packages(self):
        assert parse_lock_packages("") == []
        assert parse_lock_packages("packages:\n") == []
        assert parse_lock_packages("sdks:\n  dart: \"x\"\n") == []

    def test_unquoted_version_and_sdk_description(self):
        text = "\n".join(
            [
                "packages:",
                "  foo:",
                "    dependency: direct main",
                "    description: flutter",
                "    source: sdk",
                "    version: 0.0.0",
            ]
        )
        pkgs = parse_lock_packages(text)
        assert len(pkgs) == 1
        assert pkgs[0].name == "foo"
        assert pkgs[0].version == "0.0.0"
        assert pkgs[0].source == "sdk"

    def test_stray_indented_line_does_not_break(self):
        text = "\n".join(
            [
                "packages:",
                "  foo:",
                "    dependency: transitive",
                "    description:",
                "      name: foo",
                "    source: hosted",
                '    version: "1.0.0"',
                "  ~broken-line",
                "  bar:",
                "    dependency: transitive",
                "    source: hosted",
                '    version: "2.0.0"',
            ]
        )
        pkgs = parse_lock_packages(text)
        assert [p.name for p in pkgs] == ["foo", "bar"]

    def test_blank_line_inside_packages_section(self):
        text = "\n".join(
            [
                "packages:",
                "",
                "  foo:",
                "    dependency: transitive",
                "    source: hosted",
                '    version: "1.0.0"',
                "",
                "  bar:",
                "    dependency: transitive",
                "    source: hosted",
                '    version: "2.0.0"',
            ]
        )
        pkgs = parse_lock_packages(text)
        assert [p.name for p in pkgs] == ["foo", "bar"]

    def test_invalid_indented_line_before_first_entry_is_skipped(self):
        text = "\n".join(
            [
                "packages:",
                "  ???",
                "  foo:",
                "    dependency: transitive",
                "    source: hosted",
                '    version: "1.0.0"',
            ]
        )
        pkgs = parse_lock_packages(text)
        assert [p.name for p in pkgs] == ["foo"]


